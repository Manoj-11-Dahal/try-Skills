#!/usr/bin/env python3
"""Reconcile current catalog metadata with disk; never edit or move a skill.

Read-only by default. Historical research/assignment reports are not rewritten.
"""
from __future__ import annotations

import argparse
import re
from collections import Counter
from pathlib import Path

from reorganize_skills_by_category import build_index_browse
from tree_navigation import MARKER, overview, branch_pages
from topic_tree import TOPIC_DIR, build_topics
from skill_categories import CATEGORIES
from skill_taxonomy import SUBCATEGORY_LABELS
from validate_skills import ROOT, discover_skills, parse_frontmatter

SKILL_LINK = re.compile(r"\[([^\]]+)\]\((skills/[^)\s]+/SKILL\.md)\)")


def inventory(root: Path) -> tuple[dict[str, tuple[str, str]], Counter, Counter]:
    records = {}
    counts: Counter[str] = Counter()
    subcounts: Counter[tuple[str, str]] = Counter()
    for path in discover_skills(root / "skills"):
        parts = path.relative_to(root / "skills").parts
        name, description, _, errors = parse_frontmatter(path)
        if errors or len(parts) != 4 or parts[0] not in CATEGORIES or parts[1] not in SUBCATEGORY_LABELS[parts[0]] or name != parts[2]:
            raise ValueError(f"invalid skill metadata/layout: {path}: {errors}")
        if name in records:
            raise ValueError(f"duplicate skill name: {name}")
        records[name] = (path.relative_to(root).as_posix(), description)
        counts[parts[0]] += 1
        subcounts[parts[:2]] += 1
    if not records:
        raise ValueError("no skill files found; refusing to empty the catalog")
    return records, counts, subcounts


def sync_index(text: str, records: dict[str, tuple[str, str]], counts: Counter, subcounts: Counter) -> str:
    """Preserve existing routing descriptions/order, repair paths, append new skills."""
    seen = set()
    lines = []
    for line in text.splitlines():
        match = SKILL_LINK.search(line)
        if match:
            if not line.startswith("|") or len(SKILL_LINK.findall(line)) != 1:
                raise ValueError("expected exactly one skill link per catalog table row")
            name = Path(match[2]).parent.name
            if name not in records or name in seen:
                continue
            seen.add(name)
            line = SKILL_LINK.sub(lambda _: f"[{name}]({records[name][0]})", line)
        lines.append(line)
    for name in sorted(records.keys() - seen):
        path, description = records[name]
        # HTML entity avoids introducing an extra Markdown table column.
        lines.append(f"| {description.replace('|', '&#124;')} | [{name}]({path}) |")
    updated = "\n".join(lines) + "\n"
    pattern = r"(?ms)^## Browse by category\n.*?(?=^\| If the task is about… \| Load \|)"
    updated, replacements = re.subn(pattern, lambda _: build_index_browse(counts, subcounts), updated, count=1)
    if replacements != 1:
        raise ValueError("catalog browse section/table header is missing")
    return updated


def distribution(counts: Counter, subcounts: Counter) -> str:
    total = sum(counts.values())
    lines = [
        "## Total Skills by Category", "",
        "<!-- Generated by scripts/sync_catalog.py; do not edit counts manually. -->", "",
        "| Rank | Category | Subcategories | Skills | % of Total |",
        "|---:|---|---:|---:|---:|",
    ]
    ordered = sorted(CATEGORIES, key=lambda category: (-counts[category], category))
    for rank, category in enumerate(ordered, 1):
        subcategory_count = sum(1 for cat, _ in subcounts if cat == category)
        lines.append(f"| {rank} | [{CATEGORIES[category]}](skills/{category}/) | {subcategory_count} | {counts[category]:,} | {counts[category] / total:.1%} |")
    lines.extend([f"| | **Total** | **{len(subcounts)}** | **{total:,}** | **100%** |", "", "<details>", "<summary>Visual distribution</summary>", "", "```text"])
    for category in ordered:
        bar = "█" * max(1, round(30 * counts[category] / max(counts.values())))
        lines.append(f"{CATEGORIES[category]:<33} {bar:<30} {counts[category]:>6,} ({counts[category] / total:.1%})")
    lines.extend(["```", "", "</details>", "", ""])
    return "\n".join(lines)


def repository_tree(counts: Counter, subcounts: Counter) -> str:
    lines = ["## Repository Structure", "", "```text", "try-Skills/",
             "├── .github/workflows/       # Automated quality checks",
             "├── assets/                  # SVG banner and workflow animation",
             "├── references/              # Provenance and historical reports",
             "├── scripts/                 # Validation and tree generation",
             f"├── skills/                  # {sum(counts.values()):,} current packages"]
    for category in CATEGORIES:
        if counts[category]:
            lines.append(f"│   ├── {category}/ # {counts[category]:,}")
    lines.extend(["│   └── README.md            # Library overview",
                  "├── tests/                   # Standard-library test suite",
                  "├── INDEX.md                 # Expandable skill tree",
                  "├── CONTRIBUTING.md          # Maintenance guide",
                  "└── README.md", "```", "",
                  "Inside each subject:", "", "```text", "skills/<category>/<subject>/",
                  "├── README.md                # Topic branches and breadcrumbs",
                  "├── _topics/", "│   └── <topic-key>.md        # Context groups and skill links",
                  "└── <skill-name>/", "    └── SKILL.md             # Instructions to load", "```", "", ""])
    return "\n".join(lines)


def replace_section(text: str, heading: str, replacement: str) -> str:
    pattern = rf"(?ms)^## {re.escape(heading)}\n.*?(?=^## |\Z)"
    updated, count = re.subn(pattern, lambda _: replacement, text, count=1)
    if count != 1:
        raise ValueError(f"missing README section: {heading}")
    return updated


def update_total(text: str, total: int) -> str:
    text = re.sub(r"\b[\d,]+\+?(?= (?:named `SKILL.md` packages|task-focused workflows|workflows for tool-using agents))", f"{total:,}", text)
    text = re.sub(r'(?<=alt=")[\d,]+\+?(?= skills")', f"{total:,}", text)
    text = re.sub(r"(?<=Browse all )[\d,]+\+?(?= skills\b)", f"{total:,}", text)
    return re.sub(r"(?<=badge/SKILLS-)[\d%CB]+(?=-)", f"{total:,}".replace(",", "%2C"), text)


def catalog_counts(counts: Counter, subcounts: Counter, topics) -> dict[str, int]:
    return {
        "categories": sum(bool(n) for n in counts.values()),
        "subjects": sum(bool(n) for n in subcounts.values()),
        "topics": sum(map(len, topics.values())),
        "groups": sum(len(topic.groups) for items in topics.values() for topic in items),
        "skills": sum(counts.values()),
    }


def library_summary(counts: Counter, subcounts: Counter, topics) -> str:
    values = catalog_counts(counts, subcounts, topics)
    return "\n".join([
        "## Library at a Glance", "",
        "<!-- Generated by scripts/sync_catalog.py; counts come from the current checkout. -->", "",
        "| Categories | Subjects | Topics | Context / workflow groups | Skills |",
        "|---:|---:|---:|---:|---:|",
        "| " + " | ".join(f"**{value:,}**" for value in values.values()) + " |", "",
        "[Browse every branch](INDEX.md) · [How the tree is organized](references/multi-level-tree-2026-10-14.md)", "", "",
    ])


def update_banner(text: str, counts: Counter, subcounts: Counter, topics) -> str:
    """Keep explicit SVG statistic nodes current without rewriting the artwork."""
    text = update_total(text, sum(counts.values()))
    if "data-count=" not in text:
        return text  # Older banners and minimal maintenance fixtures.
    values = catalog_counts(counts, subcounts, topics)
    if set(re.findall(r'data-count="([^"]+)"', text)) != set(values):
        raise ValueError("banner statistic keys must be categories, subjects, topics, groups, skills")
    for key, value in values.items():
        pattern = rf'(<text\b[^>]*\bdata-count="{key}"[^>]*>)[^<]*(</text>)'
        text, replaced = re.subn(pattern, lambda match: f"{match[1]}{value:,}{match[2]}", text)
        if replaced != 1:
            raise ValueError(f"banner needs exactly one text node for statistic {key!r}")
    return text


def planned_updates(root: Path) -> dict[Path, str]:
    records, counts, subcounts = inventory(root)
    topics = build_topics(root, records)
    readme = (root / "README.md").read_text(encoding="utf-8")
    if "## Library at a Glance\n" in readme:
        readme = replace_section(readme, "Library at a Glance", library_summary(counts, subcounts, topics))
    readme = replace_section(readme, "Total Skills by Category", distribution(counts, subcounts))
    readme = replace_section(readme, "Repository Structure", repository_tree(counts, subcounts))
    readme = update_total(readme, len(records))
    readme = re.sub(r"\*\*\d+ subject subfolders\*\*", f"**{len(subcounts)} subject subfolders**", readme)
    readme = re.sub(r"\*\*(?:nine|twelve|\d+) top-level categories\*\*", f"**{len(CATEGORIES)} top-level categories**", readme)
    updates = {
        root / "INDEX.md": overview(counts, subcounts, from_root=True, topics=topics),
        root / "skills/README.md": overview(counts, subcounts, topics=topics),
        root / "README.md": readme,
        root / "assets/agentic-skills-banner.svg": update_banner((root / "assets/agentic-skills-banner.svg").read_text(encoding="utf-8"), counts, subcounts, topics),
    }
    updates.update(branch_pages(root, records, counts, subcounts, topics))
    return updates


def obsolete_topic_pages(root: Path, updates) -> list[Path]:
    """Only prune our generated topic indexes, never user-authored documents."""
    return sorted(path for path in (root / "skills").glob(f"*/*/{TOPIC_DIR}/*.md")
                  if path not in updates and MARKER in path.read_text(encoding="utf-8"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="check for drift without writing (default)")
    mode.add_argument("--write", action="store_true", help="refresh current metadata; never rewrite skills")
    args = parser.parse_args()
    try:
        updates = planned_updates(ROOT)
        obsolete = obsolete_topic_pages(ROOT, updates)
        for path in updates:
            if path.parent.name == TOPIC_DIR and path.exists() and MARKER not in path.read_text(encoding="utf-8"):
                raise ValueError(f"refusing to overwrite a user-authored topic page: {path}")
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"FAIL: {exc}")
        return 1
    stale = {path: content for path, content in updates.items() if not path.exists() or path.read_text(encoding="utf-8") != content}
    for path, content in stale.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        print(f"{'Updated' if args.write else 'STALE'}: {path.relative_to(ROOT)}")
    for path in obsolete:
        if args.write:
            path.unlink()
        print(f"{'Removed obsolete generated page' if args.write else 'OBSOLETE'}: {path.relative_to(ROOT)}")
    if not stale and not obsolete:
        print("Category tree, all navigation pages, README, and banner are up to date.")
    elif not args.write:
        print("Run python scripts/sync_catalog.py --write and review the diff.")
    return int(bool(stale or obsolete) and not args.write)


if __name__ == "__main__":
    raise SystemExit(main())
