"""Linked multi-level trees for all skills, without moving package folders."""
from __future__ import annotations

from html import escape
from pathlib import Path

from skill_tree import CATEGORIES, CATEGORY_DESCRIPTIONS
from skill_taxonomy import SUBCATEGORY_LABELS
from topic_tree import TOPIC_DIR, build_topics

MARKER = "<!-- skill-tree:v1; generated by scripts/sync_catalog.py -->"


def tree_lines(counts, subcounts, topics=None) -> list[str]:
    lines = ["skills/"]
    categories = [category for category in CATEGORIES if counts[category]]
    for i, category in enumerate(categories):
        last = i == len(categories) - 1
        lines.append(f"{'└──' if last else '├──'} {category}/ ({counts[category]:,})")
        prefix = "    " if last else "│   "
        branches = [branch for branch in SUBCATEGORY_LABELS[category] if subcounts[category, branch]]
        for j, branch in enumerate(branches):
            branch_last = j == len(branches) - 1
            lines.append(f"{prefix}{'└──' if branch_last else '├──'} {branch}/ ({subcounts[category, branch]:,})")
            if topics is not None:
                items = topics.get((category, branch), [])
                child_prefix = prefix + ("    " if branch_last else "│   ")
                for k, topic in enumerate(items):
                    lines.append(f"{child_prefix}{'└──' if k == len(items) - 1 else '├──'} {topic.label} ({topic.count:,})")
    return lines


def overview(counts, subcounts, *, from_root: bool = False, topics=None) -> str:
    prefix = "skills/" if from_root else ""
    topic_total = sum(map(len, topics.values())) if topics is not None else None
    stats = f"**{sum(counts.values()):,} skills · {sum(bool(counts[c]) for c in CATEGORIES)} categories · {sum(bool(n) for n in subcounts.values())} subjects"
    stats += f" · {topic_total:,} topics**" if topic_total is not None else "**"
    lines = ["# Skill Tree" if from_root else "# Explore the Skill Library", "", MARKER, "", stats, "",
             "> Category → Subject → Topic → Context / workflow group → Skill", "",
             "Follow the expandable branches below. Every skill is listed on one topic page, with breadcrumbs back through the tree.", "",
             "[Project overview](README.md) · [Browse folders](skills/README.md)" if from_root else "[Project overview](../README.md) · [Skill tree](../INDEX.md)", "",
             "## Choose a category", "", "| Category | What you can do | Skills |", "|---|---|---:|"]
    for category, label in CATEGORIES.items():
        if counts[category]:
            lines.append(f"| [{label}]({prefix}{category}/README.md) | {CATEGORY_DESCRIPTIONS[category]} | {counts[category]:,} |")
    lines.extend(["", "## Tree at a glance", "", "```text", *tree_lines(counts, subcounts), "```", "",
                  "## Expand the multi-level tree", "", "Open a category, then a subject, then a topic. Topic pages contain the final context and skill branches.", ""])
    for category, label in CATEGORIES.items():
        if not counts[category]:
            continue
        lines.extend(["<details>", f"<summary><strong>{escape(label)}</strong> · {counts[category]:,} skills</summary>", "",
                      f"[Open {label}]({prefix}{category}/README.md)", ""])
        for branch, branch_label in SUBCATEGORY_LABELS[category].items():
            if not subcounts[category, branch]:
                continue
            items = topics.get((category, branch), []) if topics is not None else []
            lines.extend(["<details>", f"<summary>{escape(branch_label)} · {subcounts[category, branch]:,} skills</summary>", "",
                          f"[Open subject]({prefix}{category}/{branch}/README.md)", ""])
            for topic in items:
                lines.append(f"- [{escape(topic.label)}]({prefix}{category}/{branch}/{TOPIC_DIR}/{topic.key}.md) — {topic.count:,} skills · {len(topic.groups)} groups")
            lines.extend(["", "</details>", ""])
        lines.extend(["</details>", ""])
    lines.extend(["## Navigation versus storage", "", "```text", "Category", "└── Subject", "    └── Topic", "        └── Context or workflow group", "            └── Skill → SKILL.md", "```", "",
                  "Topic pages are browsing indexes under each subject's `_topics/` folder, not additional skill packages. Actual packages stay at `skills/<category>/<subject>/<skill-name>/SKILL.md`; names, instructions, and installation paths are unchanged by topic grouping.", "",
                  "Topic labels use existing authoring metadata and stable name families. Name-prefix groups are explicitly labeled; they are not semantic reclassifications. Context/workflow lists contain at most 40 skills each.", ""])
    return "\n".join(lines)


def compact(text: str, limit: int = 160) -> str:
    text = " ".join(text.split()).replace("|", "&#124;").replace("<", "&lt;").replace(">", "&gt;")
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + "…"


def topic_page(category, branch, topic, records) -> str:
    label = CATEGORIES[category]
    branch_label = SUBCATEGORY_LABELS[category][branch]
    lines = [f"# {escape(topic.label)}", "", MARKER, "",
             f"[Home](../../../../README.md) / [Categories](../../../README.md) / [{label}](../../README.md) / [{branch_label}](../README.md) / {escape(topic.label)}", "",
             f"**{topic.count:,} skills · {len(topic.groups)} context / workflow groups**", "",
             f"Grouping basis: {topic.method}. This is navigation only; package instructions are unchanged.", "",
             "## Follow a sub-branch", ""]
    for i, (group, names) in enumerate(topic.groups.items(), 1):
        lines.append(f"- [{escape(group)}](#group-{i}) — {len(names)} skills")
    lines.extend(["", "## Skill branches", "", "Expand a sub-branch and open a skill. Summaries are shortened; the linked package contains the complete workflow.", ""])
    for i, (group, names) in enumerate(topic.groups.items(), 1):
        lines.extend([f'<a id="group-{i}"></a>', "<details open>", f"<summary><strong>{escape(group)}</strong> · {len(names)} skills</summary>", ""])
        for j, name in enumerate(names):
            connector = "└──" if j == len(names) - 1 else "├──"
            lines.extend([f"- `{connector}` [{name}](../{name}/SKILL.md)", f"  - {compact(records[name][1])}"])
        lines.extend(["", "</details>", ""])
    lines.extend(["---", "", f"[↑ {branch_label}](../README.md) · [↑ {label}](../../README.md) · [↑ All categories](../../../README.md)", ""])
    return "\n".join(lines)


def branch_pages(root: Path, records, counts, subcounts, topics=None) -> dict[Path, str]:
    topics = build_topics(root, records) if topics is None else topics
    pages = {}
    for category, label in CATEGORIES.items():
        if not counts[category]:
            continue
        topic_count = sum(len(items) for (cat, _), items in topics.items() if cat == category)
        lines = [f"# {label}", "", MARKER, "",
                 "[Home](../../README.md) / [All categories](../README.md) / " + label, "",
                 CATEGORY_DESCRIPTIONS[category], "",
                 f"**{counts[category]:,} skills · {topic_count} topics**", "",
                 "## Follow a subject branch", "", "| Subject | Topics | Skills |", "|---|---:|---:|"]
        for branch, branch_label in SUBCATEGORY_LABELS[category].items():
            if subcounts[category, branch]:
                lines.append(f"| [{branch_label}]({branch}/README.md) | {len(topics[category, branch])} | {subcounts[category, branch]:,} |")
        category_counts = {cat: counts[category] if cat == category else 0 for cat in CATEGORIES}
        lines.extend(["", "## Category → subject → topic", "", "The tree below shows navigation branches, not extra package directories.", "",
                      "```text", *tree_lines(category_counts, subcounts, topics), "```", "",
                      "Follow a subject above to reach its topic pages, context groups, and individual skills.", ""])
        pages[root / "skills" / category / "README.md"] = "\n".join(lines)
        for branch, branch_label in SUBCATEGORY_LABELS[category].items():
            items = topics.get((category, branch), [])
            if not items:
                continue
            lines = [f"# {branch_label}", "", MARKER, "",
                     f"[Home](../../../README.md) / [All categories](../../README.md) / [{label}](../README.md) / {branch_label}", "",
                     f"**{subcounts[category, branch]:,} skills · {len(items)} topic branches**", "",
                     "## Topic branches", "", "Follow a topic, choose a context or workflow group, then open a skill. All packages in this subject appear exactly once across these topic pages.", ""]
            for topic in items:
                target = f"{TOPIC_DIR}/{topic.key}.md"
                lines.extend(["<details>", f"<summary><strong>{escape(topic.label)}</strong> · {topic.count} skills</summary>", "",
                              f"[Open topic]({target})", ""])
                for i, (group, names) in enumerate(topic.groups.items(), 1):
                    lines.append(f"- [{escape(group)}]({target}#group-{i}) — {len(names)} skills")
                lines.extend(["", "</details>", ""])
                pages[root / "skills" / category / branch / TOPIC_DIR / f"{topic.key}.md"] = topic_page(category, branch, topic, records)
            lines.extend(["---", "", f"[↑ {label}](../README.md) · [↑ All categories](../../README.md)", ""])
            pages[root / "skills" / category / branch / "README.md"] = "\n".join(lines)
    return pages
